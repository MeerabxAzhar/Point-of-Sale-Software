    private void txtsearchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtsearchKeyReleased
         String txt=txtsearch.getText();
          try {
              if(txt.matches("^[0-9]+$")){
            String query="SELECT * FROM `welding` Where `Model No`="+txt;
                pst=con.prepareStatement(query);
              rs=pst.executeQuery();
              tblw.setModel(DbUtils.resultSetToTableModel(rs));
              }
            else if (txt.matches("^[a-zA-Z0-9]+$")) {
    // Search by ID
    String query = "SELECT * FROM `welding` WHERE `Id` = '" + txt + "'";
    pst = con.prepareStatement(query);
              rs=pst.executeQuery();
              tblw.setModel(DbUtils.resultSetToTableModel(rs));
              }
               if(txt.matches("^[a-zA-Z]+$"))
              {
              String query="SELECT * FROM `welding` Where `Name` LIKE '%"+txt+"%'";
                pst=con.prepareStatement(query);
              rs=pst.executeQuery();
              tblw.setModel(DbUtils.resultSetToTableModel(rs));
              }
               if (txt.isEmpty()) {
    String query = "SELECT * FROM `welding`";
    pst = con.prepareStatement(query);
    rs = pst.executeQuery();
    tblw.setModel(DbUtils.resultSetToTableModel(rs));}
            } catch (SQLException ex) {
                Logger.getLogger(Welding.class.getName()).log(Level.SEVERE, null, ex);
            }
    }//GEN-LAST:event_txtsearchKeyReleased

    private void btnaddMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnaddMouseClicked
     try {
              String Id = txtid.getText();
            String ItemName = txtin.getText();
            String Brand = (String) combobrand.getSelectedItem();
            String ModelNo = txtmn.getText();
            String WholeSale = txtws.getText();
            String RSale = txtrs.getText();
            String CostPrice = txtcp.getText();
            String ShowRoom = txtsr.getText();
            String Godam = txtgodam.getText();
            int TotalQuantity = Integer.parseInt(txtsr.getText()) + Integer.parseInt(txtgodam.getText());
            Double TotalCost = Double.parseDouble(txtcp.getText()) * TotalQuantity;
            pst = con.prepareStatement("INSERT INTO `welding`(`Id`,`Name`, `Brand`, `Model No`, `Whole Sale`, `R Sale`, `Cost Price`, `Total Quantity`, `Show Room`, `Godam`, `Total Cost`) VALUES (?,?,?,?,?,?,?,?,?,?,?)");
pst.setString(1, Id);
            pst.setString(2, ItemName);
            pst.setString(3, Brand);
            pst.setString(4, ModelNo);
            pst.setString(5, WholeSale);
            pst.setString(6, RSale);
            pst.setString(7, CostPrice);
            pst.setInt(8, TotalQuantity);
            pst.setString(9, ShowRoom);
            pst.setString(10, Godam);
            pst.setDouble(11, TotalCost);
            JOptionPane.showMessageDialog(this, "Added successfully!");
            pst.executeUpdate();
             txtid.setText("");
            txtin.setText("");
            combobrand.setSelectedItem("Choose a Brand");
            txtmn.setText("");
            txtws.setText("");
            txtrs.setText("");
            txtcp.setText("");
            txtsr.setText("");
            txtgodam.setText("");
            tbl();
        } catch (SQLException ex) {
            Logger.getLogger(WeldingFields.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnaddMouseClicked

