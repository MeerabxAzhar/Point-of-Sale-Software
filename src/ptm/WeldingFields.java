            String ShowRoom = txtsr.getText();
            String Godam = txtgodam.getText();
            int TotalQuantity = Integer.parseInt(txtsr.getText()) + Integer.parseInt(txtgodam.getText());
            Double TotalCost = Double.parseDouble(txtcp.getText()) * TotalQuantity;
            pst = con.prepareStatement("UPDATE `welding` SET `Id`=?,`Name`=?,`Brand`=?,`Whole Sale`=?,`R Sale`=?,`Cost Price`=?,`Total Quantity`=?,`Show Room`=?,`Godam`=?,`Total Cost`=? WHERE `Model No`=?");
            pst.setString(1, Id);
            pst.setString(2, ItemName);
            pst.setString(3, Brand);
            pst.setString(11, ModelNo);
            pst.setString(4, WholeSale);
            pst.setString(5, RSale);
            pst.setString(6, CostPrice);
            pst.setInt(7, TotalQuantity);
            pst.setString(8, ShowRoom);
            pst.setString(9, Godam);
            pst.setDouble(10, TotalCost);
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Updated successfully!");
            btnupdate.setEnabled(true);
            txtid.setText("");
            txtin.setText("");
            combobrand.setSelectedItem("Choose a Brand");
            txtmn.setText("");
            txtws.setText("");
            txtrs.setText("");
            txtcp.setText("");
            txtsr.setText("");
            txtgodam.setText("");
